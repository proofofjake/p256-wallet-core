#!/usr/bin/env python3
"""Generates src/unicode_table.rs: the characters review text shows as themselves.

Everything else is escaped by `review::sanitize`. A character is shown if it is assigned to a letter, mark, number,
punctuation or symbol category (L*, M*, N*, P*, S*) and isn't Default_Ignorable_Code_Point, or it is the ASCII
space. Unassigned code points are escaped too, so characters added in a later Unicode version stay escaped until
this table is regenerated.

Usage: scripts/unicode-table.py <dir>   where <dir> holds DerivedGeneralCategory.txt and DerivedCoreProperties.txt
from https://www.unicode.org/Public/UCD/latest/ucd/ (the first is under extracted/).
"""

import re
import sys
from pathlib import Path

SHOWN_CATEGORIES = ("L", "M", "N", "P", "S")
# Symbols that render as blank space without being Default_Ignorable.
BLANK_SYMBOLS = {0x2800}  # BRAILLE PATTERN BLANK


def ranges(path, keep):
    """Yields (first, last) for every data line whose value satisfies `keep`."""
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        codes, value = (part.strip() for part in line.split(";")[:2])
        if keep(value):
            first, _, last = codes.partition("..")
            yield int(first, 16), int(last or first, 16)


def version(path):
    match = re.search(r"-(\d+\.\d+\.\d+)\.txt", path.read_text().splitlines()[0])
    return match.group(1)


def main():
    source = Path(sys.argv[1])
    categories = source / "DerivedGeneralCategory.txt"
    properties = source / "DerivedCoreProperties.txt"
    if version(categories) != version(properties):
        sys.exit("The two files are from different Unicode versions")

    shown = set()
    for first, last in ranges(categories, lambda c: c.startswith(SHOWN_CATEGORIES)):
        shown.update(range(first, last + 1))
    for first, last in ranges(properties, lambda p: p == "Default_Ignorable_Code_Point"):
        shown.difference_update(range(first, last + 1))
    shown -= BLANK_SYMBOLS
    shown.add(0x20)

    merged = []
    for code in sorted(shown):
        if merged and merged[-1][1] == code - 1:
            merged[-1][1] = code
        else:
            merged.append([code, code])

    lines = [
        "//! Generated by scripts/unicode-table.py from the Unicode Character Database. Don't edit by hand.",
        "//!",
        "//! The characters review text shows as themselves: assigned letters, marks, numbers, punctuation and symbols",
        "//! that aren't default-ignorable, plus the ASCII space. `review::sanitize` escapes everything else.",
        "",
        f'pub const UNICODE_VERSION: &str = "{version(categories)}";',
        "",
        "/// Inclusive code point ranges, sorted and non-overlapping.",
        "#[rustfmt::skip]",
        "pub const SHOWN: &[(u32, u32)] = &[",
    ]
    row = []
    for first, last in merged:
        row.append(f"(0x{first:x}, 0x{last:x}),")
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    output = Path(__file__).resolve().parent.parent / "src" / "unicode_table.rs"
    output.write_text("\n".join(lines) + "\n")
    print(f"{output}: Unicode {version(categories)}, {len(merged)} ranges, {len(shown)} characters")


if __name__ == "__main__":
    main()
